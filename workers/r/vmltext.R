vml_diag <- function(...) {
  cat(..., "\n", sep = "", file = stderr())
  flush(stderr())
  invisible(NULL)
}

vml_fatal <- function(...) {
  vml_diag(...)
  quit(save = "no", status = 1L, runLast = FALSE)
}

# The code-point slice helper. R's x[a:b] counts DOWN when a > b, which turns "empty slice" into
# "two characters in the wrong order", and x[beyond the end] pads with NA, which turns a scan into a
# "missing value where TRUE/FALSE needed" crash. Both are silent hazards in a hand-written scanner,
# so both are closed here, once.
vml_slice <- function(x, a, b) {
  if (b < a) return(x[0L])
  n <- length(x)
  if (a > n) return(x[0L])
  if (b > n) b <- n
  x[a:b]
}

vml_is_ascii_letter <- function(cp) (cp >= 65L & cp <= 90L) | (cp >= 97L & cp <= 122L)
vml_is_ascii_digit <- function(cp) cp >= 48L & cp <= 57L
vml_is_ascii_alnum <- function(cp) vml_is_ascii_letter(cp) | vml_is_ascii_digit(cp)
# JavaScript's \w: ASCII letters, digits and underscore. Used for the word-boundary test.
vml_is_word_cp <- function(cp) vml_is_ascii_alnum(cp) | cp == 95L
vml_is_hex_digit <- function(cp) vml_is_ascii_digit(cp) | (cp >= 65L & cp <= 70L) | (cp >= 97L & cp <= 102L)
vml_hex_value <- function(cp) if (cp <= 57L) cp - 48L else vml_ascii_lower(cp) - 87L

vml_ascii_lower <- function(cps) {
  if (is.raw(cps)) cps <- as.integer(cps)
  up <- cps >= 65L & cps <= 90L
  if (any(up)) cps[up] <- cps[up] + 32L
  cps
}

