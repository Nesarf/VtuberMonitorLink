VML_DASHES <- c(0x2010L:0x2015L, 0x2212L)

vml_is_deleted_cp <- function(cp) {
  for (r in VML_DELETE_RANGES) if (cp >= r[1L] && cp <= r[2L]) return(TRUE)
  FALSE
}

vml_map_one <- function(cp) {
  if (cp %in% VML_SPACE_LIKE) return(VML_SPACE)
  if (cp >= 0xFF01L && cp <= 0xFF5EL) return(as.integer(cp - 0xFEE0L))
  if (cp %in% VML_SINGLE_QUOTES) return(VML_SQUOTE)
  if (cp %in% VML_DOUBLE_QUOTES) return(VML_DQUOTE)
  if (cp %in% VML_DASHES) return(VML_DASH)
  if (cp == 0x2026L) return(A("..."))
  if (cp == 0x3001L) return(44L)
  if (cp == 0x3002L) return(46L)
  as.integer(cp)
}

vml_map_mask <- function(cps) {
  (cps %in% VML_SPACE_LIKE) |
    (cps >= 0xFF01L & cps <= 0xFF5EL) |
    (cps %in% VML_SINGLE_QUOTES) | (cps %in% VML_DOUBLE_QUOTES) | (cps %in% VML_DASHES) |
    (cps == 0x2026L) | (cps == 0x3001L) | (cps == 0x3002L)
}

# Replace the positions in idx with the corresponding (possibly multi-code-point) replacements.
vml_expand_at <- function(x, idx, reps) {
  if (length(idx) == 0L) return(x)
  n <- length(x)
  out <- vector("list", 0L)
  k <- 0L
  prev <- 1L
  for (t in seq_along(idx)) {
    p <- idx[t]
    if (p > prev) { k <- k + 1L; out[[k]] <- x[prev:(p - 1L)] }
    k <- k + 1L
    out[[k]] <- reps[[t]]
    prev <- p + 1L
  }
  if (prev <= n) { k <- k + 1L; out[[k]] <- x[prev:n] }
  unlist(out[seq_len(k)], use.names = FALSE)
}

vml_normalize_cps <- function(cps) {
  n <- length(cps)
  if (n == 0L) return(integer(0))

  # 1. delete
  keep <- !vapply(cps, vml_is_deleted_cp, logical(1))
  cps <- cps[keep]
  n <- length(cps)
  if (n == 0L) return(integer(0))

  # 2. map, one code point to one (or three, for U+2026)
  hit <- which(vml_map_mask(cps))
  if (length(hit) > 0L) cps <- vml_expand_at(cps, hit, lapply(cps[hit], vml_map_one))
  n <- length(cps)
  if (n == 0L) return(integer(0))

  # 3. lowercase, strictly from workers/spec/latin-lower.json
  sel <- which(cps <= 591L)
  if (length(sel) > 0L) {
    vals <- VML_LOWER[cps[sel] + 1L]
    ok <- vals != 0L
    if (any(ok)) cps[sel[ok]] <- vals[ok]
  }

  # 4. fold, strictly from workers/spec/latin-fold.json, applied to the result of step 3
  sel <- which(cps <= 591L)
  if (length(sel) > 0L) {
    reps <- VML_FOLD[cps[sel] + 1L]
    has <- lengths(reps) > 0L
    if (any(has)) cps <- vml_expand_at(cps, sel[has], reps[has])
  }
  n <- length(cps)
  if (n == 0L) return(integer(0))

  # 5. collapse runs of space, tab, LF and CR into one space
  ws <- cps == 32L | cps == 9L | cps == 10L | cps == 13L
  if (any(ws)) {
    drop <- ws
    drop[1L] <- FALSE
    if (n > 1L) drop[2:n] <- ws[2:n] & ws[1:(n - 1L)]
    cps[ws] <- 32L
    cps <- cps[!drop]
  }

  # 6. trim
  n <- length(cps)
  if (n > 0L && cps[1L] == 32L) cps <- cps[-1L]
  n <- length(cps)
  if (n > 0L && cps[n] == 32L) cps <- cps[-n]
  cps
}

