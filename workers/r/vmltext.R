vml_descriptor_node <- function(capability) {
  vml_jobj(list(
    protocol = vml_jnum(1L),
    capability = vml_jstr(A(capability)),
    language = vml_jstr(A("r")),
    impl = vml_jstr(A("table-driven")),
    runtime = vml_jstr(vml_utf8_decode(charToRaw(R.version.string))),
    deterministic = vml_jbool(TRUE)
  ))
}

vml_error_node <- function(id_node, code, message) {
  vml_jobj(list(id = id_node, ok = vml_jbool(FALSE),
                error = vml_jobj(list(code = vml_jstr(A(code)), message = vml_jstr(A(message))))))
}

vml_invoke <- function(capability, input_node) {
  if (identical(capability, "text.normalize")) {
    text <- vml_as_string(vml_obj_get(input_node, "text"))
    if (is.null(text)) return(list(ok = FALSE, code = "bad-input", message = "input.text must be a string"))
    return(list(ok = TRUE, output = vml_jobj(list(text = vml_jstr(vml_normalize_cps(text))))))
  }
  if (identical(capability, "text.extract")) {
    html <- vml_as_string(vml_obj_get(input_node, "html"))
    if (is.null(html)) return(list(ok = FALSE, code = "bad-input", message = "input.html must be a string"))
    base_url <- vml_obj_get(input_node, "baseUrl") # accepted, reported back nowhere, never used
    r <- vml_extract_cps(html, base_url)
    link_nodes <- lapply(r$links, function(l) {
      vml_jobj(list(href = vml_jstr(l$href), absolute = vml_jbool(l$absolute),
                    text = vml_jstr(l$text)))
    })
    return(list(ok = TRUE, output = vml_jobj(list(
      title = vml_jstr(r$title), text = vml_jstr(r$text),
      links = vml_jarr(link_nodes), images = vml_jnum(r$images)))))
  }
  if (identical(capability, "text.fingerprint")) {
    text <- vml_as_string(vml_obj_get(input_node, "text"))
    if (is.null(text)) return(list(ok = FALSE, code = "bad-input", message = "input.text must be a string"))
    f <- vml_fingerprint_cps(text)
    return(list(ok = TRUE, output = vml_jobj(list(
      simhash = vml_jstr(A(f$simhash)), tokens = vml_jnum(f$tokens), shingles = vml_jnum(f$shingles)))))
  }
  list(ok = FALSE, code = "unsupported", message = paste0("unsupported capability ", capability))
}

# Returns list(response = <code points or NULL>, stop = <logical>).
vml_handle_line <- function(cps, capability) {
  node <- tryCatch(vml_json_reader(cps), error = function(e) NULL)
  if (is.null(node)) {
    return(list(response = vml_json_encode(vml_error_node(vml_jnull(), "bad-input", "request is not JSON")),
                stop = FALSE))
  }
  id_node <- vml_obj_get(node, "id")
  if (is.null(id_node)) id_node <- vml_jnull()
  op <- vml_as_string(vml_obj_get(node, "op"))
  op_name <- if (is.null(op)) "<missing>" else rawToChar(as.raw(as.integer(op)))

  if (!is.null(op) && identical(op_name, "shutdown")) {
    # The contract shows {"id":<id>,"ok":true} for shutdown and nothing more. (The JavaScript
    # reference answers with an extra {"bye":true} output object; the Go worker reports the same
    # difference in its README, and this one follows the contract.)
    return(list(response = vml_json_encode(vml_jobj(list(id = id_node, ok = vml_jbool(TRUE)))),
                stop = TRUE))
  }
  if (!is.null(op) && identical(op_name, "describe")) {
    return(list(response = vml_json_encode(vml_jobj(list(
      id = id_node, ok = vml_jbool(TRUE), worker = vml_descriptor_node(capability)))), stop = FALSE))
  }
  if (is.null(op) || !identical(op_name, "invoke")) {
    return(list(response = vml_json_encode(vml_error_node(id_node, "unsupported",
                                                          paste0("unknown op ", op_name))), stop = FALSE))
  }

  requested <- vml_as_string(vml_obj_get(node, "capability"))
  requested_name <- if (is.null(requested)) NULL else rawToChar(as.raw(as.integer(requested)))
  if (!is.null(requested_name) && !identical(requested_name, capability)) {
    return(list(response = vml_json_encode(vml_error_node(
      id_node, "unsupported",
      paste0("this worker implements ", capability, ", not ", requested_name))), stop = FALSE))
  }
  input_node <- vml_obj_get(node, "input")
  if (is.null(input_node)) input_node <- vml_jobj(list())
  res <- tryCatch(vml_invoke(capability, input_node), error = function(e) {
    list(ok = FALSE, code = "internal", message = paste0("internal error: ", conditionMessage(e)))
  })
  if (isTRUE(res$ok)) {
    return(list(response = vml_json_encode(vml_jobj(list(id = id_node, ok = vml_jbool(TRUE),
                                                         output = res$output))), stop = FALSE))
  }
  list(response = vml_json_encode(vml_error_node(id_node, res$code, res$message)), stop = FALSE)
}

vml_serve <- function(capability) {
  incon <- file("stdin", "rb")
  on.exit(try(close(incon), silent = TRUE), add = TRUE)
  repeat {
    line <- readLines(incon, n = 1L, warn = FALSE)
    if (length(line) == 0L) break # EOF
    if (!nzchar(line)) next
    cps <- vml_utf8_decode(charToRaw(line))
    outcome <- vml_handle_line(cps, capability)
    if (!is.null(outcome$response)) {
      # One write, one flush, before the next read. Without the flush a piped stdout would hold a
      # correct answer until the process exits and the host would see a timeout, not an answer.
      cat(vml_to_native_bytes_string(outcome$response), "\n", sep = "", file = stdout())
      flush(stdout())
    }
    if (isTRUE(outcome$stop)) break
  }
  invisible(NULL)
}

# ---------------------------------------------------------------------------------------------
# 8. --selfcheck: the built-in case list. One English line per case, an "N/M checks passed"
#    summary, exit non-zero on failure, and no protocol traffic on stdout in this mode.
# ---------------------------------------------------------------------------------------------

VML_SELFCHECK_NOTE <- new.env(parent = emptyenv())

vml_selfcheck_cases <- function() {
  cases <- list()

  add <- function(name, fn) cases[[length(cases) + 1L]] <<- list(name = name, fn = fn)
  # Compares code point vectors and, on a mismatch, leaves an ASCII-safe expected/actual note for
  # the report: a console in a non-UTF-8 code page cannot be trusted to show CJK correctly.
  eq_cps <- function(actual, expected) {
    ok <- length(actual) == length(expected) && all(actual == expected)
    if (!ok) {
      VML_SELFCHECK_NOTE$text <- paste0("expected ", vml_repr(expected), ", got ", vml_repr(actual))
    }
    ok
  }

  add("normalize lowercases ASCII without its own case tables", function() {
    eq_cps(vml_normalize_cps(A("Hello, World.")), A("hello, world."))
  })
  add("normalize maps full-width ASCII (U+FF01-U+FF5E) to ASCII", function() {
    src <- as.integer(c(0xFF21L, 0xFF22L, 0xFF23L, 0xFF11L, 0xFF12L, 0xFF13L, 0xFF01L))
    eq_cps(vml_normalize_cps(src), A("abc123!"))
  })
  add("normalize deletes the zero-width space U+200B", function() {
    eq_cps(vml_normalize_cps(as.integer(c(0x61L, 0x200BL, 0x62L))), A("ab"))
  })
  add("normalize deletes combining marks so NFD equals NFC", function() {
    eq_cps(vml_normalize_cps(as.integer(c(0x65L, 0x301L))), A("e"))
  })
  add("normalize maps U+2014 to a hyphen and U+2026 to three dots", function() {
    src <- as.integer(c(0x61L, 0x2014L, 0x62L, 0x2026L, 0x63L))
    eq_cps(vml_normalize_cps(src), A("a-b...c"))
  })
  add("normalize is idempotent on an accent, full-width, zero-width mix", function() {
    src <- as.integer(c(0x2018L, 0xC9L, 0x2019L, 0x20L, 0xFF21L, 0xFF22L, 0xFF23L, 0x20L, 0x20L,
                        0x141L, 0xF3L, 0x64L, 0x17AL, 0x200BL))
    once <- vml_normalize_cps(src)
    eq_cps(vml_normalize_cps(once), once)
  })
  add("normalize leaves Han, kana and Hangul untouched", function() {
    src <- as.integer(c(0x5DF2L, 0x7ECFL, 0x5F00L, 0x64ADL, 0x4E86L, 0x20L, 0xD55CL, 0xAD6DL,
                        0xC5B4L, 0x20L, 0x30C6L, 0x30B9L, 0x30C8L))
    eq_cps(vml_normalize_cps(src), src)
  })
  add("normalize leaves Cyrillic and Arabic untouched", function() {
    src <- as.integer(c(0x41FL, 0x440L, 0x438L, 0x432L, 0x435L, 0x442L, 0x20L, 0x645L, 0x631L,
                        0x62DL, 0x628L, 0x627L))
    eq_cps(vml_normalize_cps(src), src)
  })
  add("normalize of the empty string is the empty string", function() {
    eq_cps(vml_normalize_cps(integer(0)), integer(0))
  })
  add("normalize trims and collapses whitespace to single spaces", function() {
    eq_cps(vml_normalize_cps(A("  a \t\n b \r\n  c  ")), A("a b c"))
  })
  add("extract drops script and style with their content", function() {
    r <- vml_extract_cps(A("<p>x</p><script>var a=1</script>"), NULL)
    eq_cps(r$text, A("\nx\n")) && r$images == 0L && length(r$links) == 0L
  })
  add("extract drops an unclosed tag at end of input", function() {
    eq_cps(vml_extract_cps(A("<p>a<b>b"), NULL)$text, A("\nab"))
  })
  add("extract decodes a named entity without its semicolon", function() {
    eq_cps(vml_extract_cps(A("a &amp b"), NULL)$text, A("a & b"))
  })
  add("extract decodes a decimal numeric entity (&#8212;)", function() {
    eq_cps(vml_extract_cps(A("&#8212;"), NULL)$text, as.integer(0x2014L))
  })
  add("extract decodes a hex numeric entity (&#x2014;)", function() {
    eq_cps(vml_extract_cps(A("&#x2014;"), NULL)$text, as.integer(0x2014L))
  })
  add("extract leaves an unknown entity and &copy2024 literal", function() {
    eq_cps(vml_extract_cps(A("&unknown; &copy2024"), NULL)$text, A("&unknown; &copy2024"))
  })
  add("extract closes the outer anchor when a nested one opens", function() {
    r <- vml_extract_cps(A("<a href=\"/one\">one<a href=\"/two\">two"), NULL)
    length(r$links) == 2L && eq_cps(r$links[[1L]]$href, A("/one")) &&
      eq_cps(r$links[[1L]]$text, A("one")) && !r$links[[1L]]$absolute &&
      eq_cps(r$links[[2L]]$href, A("/two")) && eq_cps(r$links[[2L]]$text, A("two")) &&
      eq_cps(r$text, A("onetwo"))
  })
  add("extract keeps CDATA as literal text and does not re-parse it", function() {
    r <- vml_extract_cps(A("<![CDATA[<b>raw</b>]]>"), NULL)
    eq_cps(r$text, A("<b>raw</b>")) && r$images == 0L
  })
  add("extract keeps an unclosed CDATA section to the end of the input", function() {
    eq_cps(vml_extract_cps(A("<![CDATA[unclosed"), NULL)$text, A("unclosed"))
  })
  add("extract drops an incomplete tag at eof, name characters included", function() {
    r1 <- vml_extract_cps(A("<p"), NULL)
    r2 <- vml_extract_cps(A("<p>abc<b"), NULL)
    length(r1$text) == 0L && eq_cps(r2$text, A("\nabc"))
  })
  add("extract keeps a lone < at eof as literal text", function() {
    eq_cps(vml_extract_cps(A("a<"), NULL)$text, A("a<"))
  })
  add("extract gives a title inside an anchor to the title alone", function() {
    r <- vml_extract_cps(A("<a href=\"/x\"><title>T</title>t</a>"), NULL)
    eq_cps(r$title, A("T")) && eq_cps(r$text, A("t")) && eq_cps(r$links[[1L]]$text, A("t"))
  })
  add("extract keeps the title out of the text and decodes entities in it", function() {
    r <- vml_extract_cps(A("<title>A &amp; B</title><p>x</p>"), NULL)
    eq_cps(r$title, A("A & B")) && eq_cps(r$text, A("\nx\n"))
  })
  add("extract counts img tags and keeps a > inside a quoted attribute", function() {
    r <- vml_extract_cps(A("<a href=\"x>y\">z</a><img src=a><IMG src=b>"), NULL)
    r$images == 2L && eq_cps(r$links[[1L]]$href, A("x>y")) && eq_cps(r$text, A("z"))
  })
  add("extract of the empty document is empty, not null", function() {
    r <- vml_extract_cps(integer(0), NULL)
    length(r$text) == 0L && length(r$title) == 0L && r$images == 0L && length(r$links) == 0L
  })
  add("fingerprint of one token is that token's own FNV-1a hash", function() {
    f <- vml_fingerprint_cps(A("x"))
    identical(f$simhash, "af63f54c86021707") && f$tokens == 1L && f$shingles == 1L
  })
  add("fingerprint of empty text is all zero bits", function() {
    f <- vml_fingerprint_cps(integer(0))
    identical(f$simhash, "0000000000000000") && f$tokens == 0L && f$shingles == 0L
  })
  add("fingerprint ignores punctuation-only tokens", function() {
    f <- vml_fingerprint_cps(A("-- !! ???"))
    f$tokens == 0L && f$shingles == 0L && identical(f$simhash, "0000000000000000")
  })
  add("fingerprint turns a 4-character CJK run into 3 bigrams", function() {
    src <- as.integer(c(0x5DF2L, 0x7ECFL, 0x5F00L, 0x64ADL))
    f <- vml_fingerprint_cps(src)
    f$tokens == 3L && f$shingles == 1L
  })
  add("fingerprint matches the reviewed snapshot for three shingles", function() {
    a <- vml_fingerprint_cps(A("a b c"))
    b <- vml_fingerprint_cps(as.integer(c(0x5DF2L, 0x7ECFL, 0x20L, 0x5DF2L, 0x7ECFL)))
    c3 <- vml_fingerprint_cps(A(paste("the quick brown fox jumps over the lazy dog while the diligent",
                                      "vtuber monitor watches every source it was told to watch and writes",
                                      "a dated report about everything it saw and everything it could not see",
                                      "because the network refused to cooperate again today")))
    identical(a$simhash, "69cf480885ad45af") && a$tokens == 3L && a$shingles == 1L &&
      identical(b$simhash, "27bfb7b6385da4c5") && b$tokens == 2L && b$shingles == 1L &&
      identical(c3$simhash, "9fe9e24f2a6ef5ca") && c3$tokens == 45L && c3$shingles == 43L
  })
  add("fingerprint counts overlapping trigram shingles", function() {
    f <- vml_fingerprint_cps(A("a b c d"))
    f$tokens == 4L && f$shingles == 2L
  })

  cases
}

vml_run_selfcheck <- function() {
  cases <- vml_selfcheck_cases()
  passed <- 0L
  for (cs in cases) {
    detail <- ""
    VML_SELFCHECK_NOTE$text <- NULL
    res <- tryCatch(cs$fn(), error = function(e) {
      detail <<- paste0(": ", conditionMessage(e))
      NULL
    })
    ok <- isTRUE(res)
    if (!ok && !nzchar(detail) && !is.null(VML_SELFCHECK_NOTE$text)) {
      detail <- paste0(": ", VML_SELFCHECK_NOTE$text)
    }
    cat(if (ok) "[ok]   " else "[FAIL] ", cs$name, detail, "\n", sep = "")
    if (ok) passed <- passed + 1L
  }
  cat(passed, "/", length(cases), " checks passed\n", sep = "")
  flush(stdout())
  if (passed != length(cases)) quit(save = "no", status = 1L, runLast = FALSE)
  invisible(TRUE)
}

