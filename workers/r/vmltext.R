vml_usage <- function() {
  paste0("usage: vmltext.R --capability <", paste(VML_CAPABILITIES, collapse = "|"), "> [--selfcheck]")
}

vml_main <- function() {
  argv <- commandArgs(trailingOnly = TRUE)
  selfcheck <- FALSE
  capability <- NULL
  i <- 1L
  while (i <= length(argv)) {
    a <- argv[[i]]
    if (identical(a, "--selfcheck")) {
      selfcheck <- TRUE
      i <- i + 1L
    } else if (identical(a, "--capability")) {
      if (i == length(argv)) {
        vml_diag("error: --capability requires a capability name")
        vml_diag(vml_usage())
        quit(save = "no", status = 2L, runLast = FALSE)
      }
      capability <- argv[[i + 1L]]
      i <- i + 2L
    } else {
      vml_diag("error: unrecognised argument '", a, "'")
      vml_diag(vml_usage())
      quit(save = "no", status = 2L, runLast = FALSE)
    }
  }

  vml_load_tables()

  if (selfcheck) {
    vml_run_selfcheck()
    quit(save = "no", status = 0L, runLast = FALSE)
  }
  if (is.null(capability)) {
    vml_diag("error: --capability <name> is required")
    vml_diag(vml_usage())
    quit(save = "no", status = 2L, runLast = FALSE)
  }
  if (!(capability %in% VML_CAPABILITIES)) {
    vml_diag("error: unknown capability '", capability, "'; this artifact implements ",
             paste(VML_CAPABILITIES, collapse = ", "))
    vml_diag(vml_usage())
    quit(save = "no", status = 2L, runLast = FALSE)
  }

  vml_serve(capability)
  quit(save = "no", status = 0L, runLast = FALSE)
}

if (!interactive()) vml_main()
