/** markdown → 完整 HTML 文档（报告主文件与「导出 HTML」共用同一套样式） */
export function htmlShell(title, md, footer = `由 Vtuber's Monitor Link 导出 · ${new Date().toISOString()}`) {
  return `<!doctype html>
<html lang="zh-CN">
<head>
<meta charset="utf-8"/>
<meta name="viewport" content="width=device-width, initial-scale=1"/>
<title>${title}</title>
<style>
${REPORT_CSS}
</style>
</head>
<body>
${markdownToHtml(md)}
<footer>${footer}</footer>
</body>
</html>`;
}

/** markdown → AsciiDoc：够用即可（标题 / 列表 / 引用 / 代码块 / 链接） */
export function markdownToAdoc(md) {
  const src = String(md ?? '').replace(/\r\n?/g, '\n');
  const out = [];
  let inFence = false;
  for (const line of src.split('\n')) {
    const fence = line.match(/^```\s*([A-Za-z0-9_+-]*)\s*$/);
    if (fence) {
      if (!inFence) {
        out.push(`[source,${fence[1] || 'text'}]`, '----');
        inFence = true;
      } else {
        out.push('----');
        inFence = false;
      }
      continue;
    }
    if (inFence) {
      out.push(line);
      continue;
    }
    const h = line.match(/^(#{1,6})\s+(.*)$/);
    if (h) {
      out.push('='.repeat(Math.min(h[1].length + 1, 6)) + ' ' + h[2]);
      continue;
    }
    if (/^\s*[-*+]\s+/.test(line)) {
      out.push(line.replace(/^(\s*)[-*+]\s+/, '$1* '));
      continue;
    }
    out.push(
      line
        .replace(/!\[([^\]]*)\]\(([^)]+)\)/g, '$1 ($2)')
        .replace(/\[([^\]]+)\]\(([^)]+)\)/g, '$1 ($2)')
        .replace(/\*\*([^*]+)\*\*/g, '*$1*')
        .replace(/`([^`]+)`/g, '`$1`'),
    );
  }
  return out.join('\n');
}

/** 一次运行的源数据文件（累积当天多次运行），主文件由它渲染而来 */
function sourceName(mode, date) {
  return `${mode === 'merch' ? 'merch-' : ''}${date}.json`;
}

function renderPrimary(cfg, source) {
  const md = source.runs.map((r) => r.markdown).join('\n\n---\n\n');
  const fmt = reportFormat(cfg);
  const title = `${source.mode === 'merch' ? '周边' : 'Vtuber 情报'} ${source.date}`;
  if (fmt === 'adoc') {
    return `// generated by Vtuber's Monitor Link at ${source.generatedAt}\n// 用 VSCode + AsciiDoc 扩展预览；纯文本阅读亦可\n\n= ${title}\n\n${markdownToAdoc(md)}\n`;
  }
  if (fmt === 'md') {
    return `<!-- generated by Vtuber's Monitor Link at ${source.generatedAt} -->\n\n${md}\n`;
  }
  return htmlShell(title, md, `由 Vtuber's Monitor Link 生成 · ${source.generatedAt} · ${source.runs.length} 次运行`);
}

export function saveReport(cfg, { markdown, mode = 'daily', date = DATE() }) {
  const dir = resolveDir(cfg, 'reportsDir');
  fs.mkdirSync(dir, { recursive: true });
  const srcFile = path.join(dir, sourceName(mode, date));
  let source = { date, mode, generatedAt: new Date().toISOString(), format: reportFormat(cfg), runs: [] };
  if (fs.existsSync(srcFile)) {
    try {
      const prev = JSON.parse(fs.readFileSync(srcFile, 'utf8'));
      if (prev && Array.isArray(prev.runs)) source = { ...prev, runs: prev.runs };
    } catch {
      // 源文件坏了就当今天第一次跑，不阻塞出报告
    }
  }
  source.runs.push({ at: new Date().toISOString(), markdown });
  source.generatedAt = new Date().toISOString();
  source.format = reportFormat(cfg);

  const primary = path.join(dir, `${sourceName(mode, date).replace(/\.json$/, '')}.${source.format}`);
  const fmt = source.format;
  fs.writeFileSync(srcFile, JSON.stringify(source, null, 2), 'utf8');
  if (fmt === 'json') return srcFile;
  fs.writeFileSync(primary, renderPrimary(cfg, source), 'utf8');
  return primary;
}

export function saveFeedFiles(cfg, date, results) {
  const dir = path.join(resolveDir(cfg, 'feedsDir'), date);
  fs.mkdirSync(dir, { recursive: true });
  const index = [];
  for (const r of results) {
    if (!r.ok || !r.content) {
      index.push({ id: r.source.id, ok: false, error: r.error ?? r.note ?? null });
      continue;
    }
    const ext = r.ext ?? 'txt';
    const file = path.join(dir, `${r.source.id}.${ext}`);
    fs.writeFileSync(file, r.content, 'utf8');
    index.push({ id: r.source.id, ok: true, file: path.relative(resolveDir(cfg, 'feedsDir'), file), bytes: r.content.length });
    void file;
  }
  fs.writeFileSync(path.join(dir, '_index.json'), JSON.stringify(index, null, 2), 'utf8');
  return { dir, index };
}

export function listReports(cfg) {
  const dir = resolveDir(cfg, 'reportsDir');
  if (!fs.existsSync(dir)) return [];
  const fmt = reportFormat(cfg);
  return fs
    .readdirSync(dir)
    .filter((f) => REPORT_EXTS.some((e) => f.endsWith(`.${e}`)))
    // 主文件本身就是 .json 时，它就是主文件，不再当侧车藏着
    .filter((f) => !f.endsWith('.json') || fmt === 'json')
    .map((f) => {
      const st = fs.statSync(path.join(dir, f));
      const ext = path.extname(f).slice(1);
      return { name: f, ext, format: ext, bytes: st.size, mtime: st.mtime.toISOString() };
    })
    .sort((a, b) => (a.name < b.name ? 1 : -1));
}

/** 读取报告原文（html 会原样返回给 iframe 渲染，其它格式给文本） */
export function readReport(cfg, name) {
  const safe = path.basename(name);
  const file = path.join(resolveDir(cfg, 'reportsDir'), safe);
  if (!fs.existsSync(file)) return null;
  return fs.readFileSync(file, 'utf8');
}

/** html → 纯文本（没有源文件时的兜底，够检索和导出用） */
function htmlToText(html) {
  return String(html ?? '')
    .replace(/<(script|style)[\s\S]*?<\/\1>/gi, '')
    .replace(/<\/(p|div|li|h[1-6]|tr|blockquote|pre)>/gi, '\n')
    .replace(/<br\s*\/?>/gi, '\n')
    .replace(/<[^>]+>/g, '')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&amp;/g, '&')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

/**
 * 取任意报告对应的 markdown 源文。
 * 这是「换格式不影响导出/检索/对比」的关键：一切主文件都由 .json 源渲染而来。
 */
export function markdownSource(cfg, name) {
  const dir = resolveDir(cfg, 'reportsDir');
  const safe = path.basename(name);
  const file = path.join(dir, safe);
  if (!fs.existsSync(file)) return null;
  const raw = fs.readFileSync(file, 'utf8');
  if (safe.endsWith('.json')) {
    try {
      const j = JSON.parse(raw);
      if (Array.isArray(j.runs)) return j.runs.map((r) => r.markdown).join('\n\n---\n\n');
      if (typeof j.markdown === 'string') return j.markdown;
      return '';
    } catch {
      return raw;
    }
  }
  const sibling = path.join(dir, `${safe.replace(/\.[^.]+$/, '')}.json`);
  if (fs.existsSync(sibling)) {
    try {
      const j = JSON.parse(fs.readFileSync(sibling, 'utf8'));
      if (Array.isArray(j.runs)) return j.runs.map((r) => r.markdown).join('\n\n---\n\n');
    } catch {
      // 落到下面的按扩展名兜底
    }
  }
  if (safe.endsWith('.md')) return raw;
  if (safe.endsWith('.adoc')) return raw.replace(/^\/\/.*$/gm, '');
  return htmlToText(raw);
}

