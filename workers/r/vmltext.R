vml_find_seq <- function(hay, needle, from = 1L) {
  m <- length(needle)
  if (m == 0L) return(NA_integer_)
  n <- length(hay)
  if (from < 1L) from <- 1L
  if (from + m - 1L > n) return(NA_integer_)
  cand <- which(hay[from:n] == needle[1L]) + from - 1L
  for (p in cand) {
    if (p + m - 1L > n) break
    if (all(hay[p:(p + m - 1L)] == needle)) return(as.integer(p))
  }
  NA_integer_
}

vml_find_cp <- function(hay, cp, from = 1L) {
  n <- length(hay)
  if (from < 1L) from <- 1L
  if (from > n) return(NA_integer_)
  w <- which(hay[from:n] == cp)
  if (length(w) == 0L) return(NA_integer_)
  as.integer(from + w[1L] - 1L)
}

vml_apply_removals <- function(src, intervals) {
  if (length(intervals) == 0L) return(src)
  keep <- rep(TRUE, length(src))
  for (iv in intervals) keep[iv[1L]:iv[2L]] <- FALSE
  src[keep]
}

# Replace each interval with its replacement text. Used by the CDATA hider, which does not delete
# the section but hides its body behind a sentinel.
vml_splice <- function(src, intervals) {
  if (length(intervals) == 0L) return(src)
  n <- length(src)
  out <- vector("list", 0L)
  k <- 0L
  prev <- 1L
  for (iv in intervals) {
    if (iv$start > prev) { k <- k + 1L; out[[k]] <- src[prev:(iv$start - 1L)] }
    if (length(iv$repl) > 0L) { k <- k + 1L; out[[k]] <- as.integer(iv$repl) }
    prev <- iv$end + 1L
  }
  if (prev <= n) { k <- k + 1L; out[[k]] <- src[prev:n] }
  if (k == 0L) return(src[0L])
  unlist(out[seq_len(k)], use.names = FALSE)
}

VML_REMOVED_ELEMENTS <- c("script", "style", "noscript", "template", "svg", "iframe")

vml_remove_one_element <- function(src, tag) {
  n <- length(src)
  if (n == 0L) return(src)
  tag_low <- vml_ascii_lower(A(tag))
  hay <- vml_ascii_lower(src)
  open_needle <- c(VML_LT, tag_low)
  close_needle <- c(VML_LT, VML_SLASH, tag_low)
  intervals <- list()
  k <- 0L
  scan <- 1L
  repeat {
    if (scan > n) break
    p <- vml_find_seq(hay, open_needle, scan)
    if (is.na(p)) break
    after <- p + length(open_needle)
    # \\b after the element name: the next character must not be a word character
    if (after <= n && vml_is_word_cp(src[after])) { scan <- p + 1L; next }
    # the open tag runs to the first '>' (the contract's regex-style pre-pass, like the reference)
    gt <- vml_find_cp(src, VML_GT, after)
    if (is.na(gt)) { scan <- p + 1L; next }
    end <- NA_integer_
    cscan <- gt + 1L
    repeat {
      q <- vml_find_seq(hay, close_needle, cscan)
      if (is.na(q)) break
      r <- q + length(close_needle)
      while (r <= n && vml_is_js_space_cp(src[r])) r <- r + 1L
      if (r <= n && src[r] == VML_GT) { end <- r; break }
      cscan <- q + 1L
    }
    if (is.na(end)) {
      # a removed element with no closing tag runs to the end of the input
      k <- k + 1L
      intervals[[k]] <- c(p, n)
      break
    }
    k <- k + 1L
    intervals[[k]] <- c(p, end)
    scan <- end + 1L
  }
  vml_apply_removals(src, intervals)
}

vml_remove_elements <- function(src) {
  for (tag in VML_REMOVED_ELEMENTS) src <- vml_remove_one_element(src, tag)
  src
}

# <![CDATA[ ... ]]> keeps its inner text - as character data, so what is inside it is literal text
# and is NOT parsed as markup afterwards. The body is therefore hidden behind a sentinel built from
# private-use code points (they cannot occur in a feed by accident) and put back at the very end,
# after every rule that could mistake it for markup has run. An unclosed section - no ]]> - keeps
# everything to the end of the input, the same principle as a removed element with no closing tag.
VML_CDATA_OPEN <- c(60L, 33L, 91L, 67L, 68L, 65L, 84L, 65L, 91L) # "<![CDATA["
VML_CDATA_CLOSE <- c(93L, 93L, 62L)                              # "]]>"
VML_SENTINEL_START <- 0xE000L
VML_SENTINEL_END <- 0xE001L

vml_cdata_hide <- function(src) {
  n <- length(src)
  bodies <- list()
  nb <- 0L
  intervals <- list()
  ki <- 0L
  scan <- 1L
  repeat {
    if (scan > n) break
    p <- vml_find_seq(src, VML_CDATA_OPEN, scan)
    if (is.na(p)) break
    q <- vml_find_seq(src, VML_CDATA_CLOSE, p + length(VML_CDATA_OPEN))
    inner_end <- if (is.na(q)) n else q - 1L
    next_pos <- if (is.na(q)) n + 1L else q + length(VML_CDATA_CLOSE)
    nb <- nb + 1L
    bodies[[nb]] <- vml_slice(src, p + length(VML_CDATA_OPEN), inner_end)
    ki <- ki + 1L
    intervals[[ki]] <- list(start = p, end = next_pos - 1L,
                            repl = c(VML_SENTINEL_START, A(vml_format_int(nb - 1L)), VML_SENTINEL_END))
    scan <- next_pos
  }
  list(src = vml_splice(src, intervals), bodies = bodies)
}

vml_cdata_restore <- function(cps, bodies) {
  if (length(bodies) == 0L || length(cps) == 0L) return(cps)
  n <- length(cps)
  intervals <- list()
  ki <- 0L
  scan <- 1L
  repeat {
    if (scan > n) break
    p <- vml_find_cp(cps, VML_SENTINEL_START, scan)
    if (is.na(p)) break
    k <- p + 1L
    while (k <= n && cps[k] >= 48L && cps[k] <= 57L) k <- k + 1L
    if (k > p + 1L && k <= n && cps[k] == VML_SENTINEL_END) {
      idx <- 0
      for (d in cps[(p + 1L):(k - 1L)]) idx <- idx * 10 + (d - 48L)
      repl <- if (idx + 1L <= length(bodies)) bodies[[idx + 1L]] else integer(0)
      ki <- ki + 1L
      intervals[[ki]] <- list(start = p, end = k, repl = repl)
      scan <- k + 1L
    } else {
      scan <- p + 1L
    }
  }
  vml_splice(cps, intervals)
}

# <!-- ... --> goes. An unterminated comment runs to the end of the input.
vml_comment_pass <- function(src) {
  open_needle <- A("<!--")
  close_needle <- A("-->")
  intervals <- list()
  k <- 0L
  scan <- 1L
  repeat {
    p <- vml_find_seq(src, open_needle, scan)
    if (is.na(p)) break
    q <- vml_find_seq(src, close_needle, p + length(open_needle))
    if (is.na(q)) {
      k <- k + 1L
      intervals[[k]] <- c(p, length(src))
      break
    }
    k <- k + 1L
    intervals[[k]] <- c(p, q + length(close_needle) - 1L)
    scan <- q + length(close_needle)
  }
  vml_apply_removals(src, intervals)
}

# <!DOCTYPE ...> goes, case-insensitively; without its '>' there is no declaration to remove.
vml_doctype_pass <- function(src) {
  open_needle <- A("<!doctype")
  hay <- vml_ascii_lower(src)
  intervals <- list()
  k <- 0L
  scan <- 1L
  repeat {
    if (scan > length(src)) break
    p <- vml_find_seq(hay, open_needle, scan)
    if (is.na(p)) break
    gt <- vml_find_cp(src, VML_GT, p + length(open_needle))
    if (is.na(gt)) { scan <- p + 1L; next }
    k <- k + 1L
    intervals[[k]] <- c(p, gt)
    scan <- gt + 1L
  }
  vml_apply_removals(src, intervals)
}

VML_NEWLINE_TAGS <- c("br", "p", "div", "li", "ul", "ol", "tr", "th", "td", "h1", "h2", "h3", "h4",
                      "h5", "h6", "section", "article", "header", "footer", "aside", "nav",
                      "blockquote", "pre", "table", "hr", "dd", "dt", "figure", "figcaption",
                      "main", "form")

VML_ENTITIES <- list(
  amp = 38L, lt = 60L, gt = 62L, quot = 34L, apos = 39L, nbsp = 0xA0L,
  mdash = 0x2014L, ndash = 0x2013L, hellip = 0x2026L, laquo = 0xABL, raquo = 0xBBL,
  copy = 0xA9L, reg = 0xAEL, trade = 0x2122L, times = 0xD7L, middot = 0xB7L
)

# Named references decode to their own character, never to the ASCII the normalizer would later
# produce: &mdash; is U+2014 here, and turning it into "-" is the normalizer's job, in another
# capability, on another day.
vml_decode_entity <- function(src, amp_index) {
  n <- length(src)
  p0 <- amp_index - 1L
  semi0 <- NA_integer_
  if (amp_index + 1L <= n) {
    w <- which(src[(amp_index + 1L):n] == VML_SEMI)
    if (length(w) > 0L) semi0 <- p0 + w[1L]
  }
  limit0 <- if (!is.na(semi0) && semi0 + 1L < p0 + 12L) semi0 + 1L else p0 + 12L
  win <- vml_slice(src, p0 + 2L, limit0)
  m <- length(win)
  if (m == 0L) return(NULL)

  body_len <- 0L
  numeric_ref <- FALSE
  hex_ref <- FALSE
  if (m >= 2L && win[1L] == VML_HASH && vml_is_ascii_digit(win[2L])) {
    k <- 2L
    while (k <= m && (k - 2L) < 7L && vml_is_ascii_digit(win[k])) k <- k + 1L
    body_len <- k - 1L
    numeric_ref <- TRUE
  } else if (m >= 3L && win[1L] == VML_HASH && (win[2L] == 120L || win[2L] == 88L) && vml_is_hex_digit(win[3L])) {
    k <- 3L
    while (k <= m && (k - 3L) < 6L && vml_is_hex_digit(win[k])) k <- k + 1L
    body_len <- k - 1L
    numeric_ref <- TRUE
    hex_ref <- TRUE
  } else if (m >= 2L && vml_is_ascii_letter(win[1L]) && vml_is_ascii_alnum(win[2L])) {
    k <- 2L
    while (k <= m && (k - 2L) < 7L && vml_is_ascii_alnum(win[k])) k <- k + 1L
    body_len <- k - 1L
  } else {
    return(NULL)
  }
  has_semi <- (body_len + 1L <= m) && win[body_len + 1L] == VML_SEMI
  body <- vml_slice(win, 1L, body_len)
  next_index <- amp_index + 1L + body_len + (if (has_semi) 1L else 0L)

  if (numeric_ref) {
    digits <- vml_slice(body, if (hex_ref) 3L else 2L, body_len)
    value <- 0
    base <- if (hex_ref) 16 else 10
    for (d in digits) value <- value * base + (if (hex_ref) vml_hex_value(d) else d - 48L)
    if (value > 0x10FFFF) return(NULL)
    if (value >= 0xD800 && value <= 0xDFFF) return(NULL)
    return(list(cps = as.integer(value), next_index = next_index))
  }
  name <- rawToChar(as.raw(as.integer(vml_ascii_lower(body))))
  if (!nzchar(name)) return(NULL)
  value <- VML_ENTITIES[[name]]
  if (is.null(value)) return(NULL)
  list(cps = as.integer(value), next_index = next_index)
}

# A buffer of code point runs, so that text is assembled in amortised constant time instead of
# growing a vector once per character.
vml_buf_new <- function() {
  b <- new.env(parent = emptyenv())
  b$items <- vector("list", 64L)
  b$n <- 0L
  b$cap <- 64L
  b
}

vml_buf_push <- function(b, cps) {
  if (length(cps) == 0L) return(invisible(NULL))
  if (b$n == b$cap) {
    b$cap <- b$cap * 2L
    length(b$items) <- b$cap
  }
  b$n <- b$n + 1L
  b$items[[b$n]] <- as.integer(cps)
  invisible(NULL)
}

vml_buf_value <- function(b) {
  if (b$n == 0L) return(integer(0))
  unlist(b$items[seq_len(b$n)], use.names = FALSE)
}

vml_tag_name <- function(raw) {
  n <- length(raw)
  i <- 1L
  if (n >= 1L && raw[1L] == VML_SLASH) i <- 2L
  while (i <= n && vml_is_js_space_cp(raw[i])) i <- i + 1L
  if (i > n) return("")
  if (!vml_is_ascii_letter(raw[i])) return("")
  j <- i
  while (j <= n && (vml_is_ascii_alnum(raw[j]) || raw[j] == VML_COLON || raw[j] == VML_DASH)) j <- j + 1L
  rawToChar(as.raw(as.integer(vml_ascii_lower(raw[i:(j - 1L)]))))
}

# /\\bhref\\s*=\\s*("..."|'...'|[^\\s>]+)/i, scanned left to right, first match wins.
vml_find_href <- function(raw) {
  n <- length(raw)
  if (n == 0L) return(integer(0))
  hay <- vml_ascii_lower(raw)
  needle <- A("href")
  start <- 1L
  repeat {
    p <- vml_find_seq(hay, needle, start)
    if (is.na(p)) return(integer(0))
    if (p > 1L && vml_is_word_cp(raw[p - 1L])) { start <- p + 1L; next }
    q <- p + length(needle)
    while (q <= n && vml_is_js_space_cp(raw[q])) q <- q + 1L
    if (q > n || raw[q] != VML_EQUALS) { start <- p + 1L; next }
    q <- q + 1L
    while (q <= n && vml_is_js_space_cp(raw[q])) q <- q + 1L
    if (q > n || raw[q] == VML_GT) { start <- p + 1L; next }
    if (raw[q] == VML_DQUOTE || raw[q] == VML_SQUOTE) {
      close <- vml_find_cp(raw, raw[q], q + 1L)
      if (is.na(close)) { start <- p + 1L; next }
      return(vml_slice(raw, q + 1L, close - 1L))
    }
    e <- q
    while (e <= n && !vml_is_js_space_cp(raw[e]) && raw[e] != VML_GT) e <- e + 1L
    return(vml_slice(raw, q, e - 1L))
  }
}

# ^[A-Za-z][A-Za-z0-9+.-]*: - "absolute" is a scheme test, not URL resolution.
vml_href_is_absolute <- function(href) {
  n <- length(href)
  if (n < 2L) return(FALSE)
  if (!vml_is_ascii_letter(href[1L])) return(FALSE)
  i <- 2L
  while (i <= n) {
    cp <- href[i]
    if (cp == VML_COLON) return(TRUE)
    if (!(vml_is_ascii_alnum(cp) || cp == 43L || cp == 46L || cp == VML_DASH)) return(FALSE)
    i <- i + 1L
  }
  FALSE
}

vml_extract_cps <- function(src, base_url) {
  # base_url is deliberately unused: the contract says href is reported verbatim, and resolving a
  # URL is a URI question, not a text question.
  invisible(base_url)
  if (length(src) == 0L) {
    return(list(title = integer(0), text = integer(0), links = list(), images = 0L))
  }
  # Pass order follows the reference implementation, not the numbering in the contract's section 3:
  # the CDATA bodies are hidden first (so nothing can mistake them for markup), then comments and
  # doctypes go, and the removed elements go last. The two orders differ only for an input where a
  # comment or doctype sits inside a removed element, or a CDATA body contains a comment opener; the
  # corpus cannot see the difference, and the reference's order is the one all implementations share.
  hidden <- vml_cdata_hide(src)
  src <- hidden$src
  cdata <- hidden$bodies
  src <- vml_comment_pass(src)
  src <- vml_doctype_pass(src)
  src <- vml_remove_elements(src)

  st <- new.env(parent = emptyenv())
  st$in_title <- FALSE
  st$title_seen <- FALSE
  st$text <- vml_buf_new()
  st$title <- vml_buf_new()
  st$pending <- NULL
  st$images <- 0L
  st$links <- list()
  st$links_n <- 0L

  push_text <- function(cps) {
    if (length(cps) == 0L) return(invisible(NULL))
    if (st$in_title) {
      # While a <title> is open its text belongs to the title and to nothing else: not to the body,
      # and not to an anchor that happens to contain it.
      vml_buf_push(st$title, cps)
      return(invisible(NULL))
    }
    vml_buf_push(st$text, cps)
    if (!is.null(st$pending)) vml_buf_push(st$pending$buf, cps)
    invisible(NULL)
  }
  close_pending <- function() {
    if (is.null(st$pending)) return(invisible(NULL))
    st$links_n <- st$links_n + 1L
    st$links[[st$links_n]] <- list(href = st$pending$href, absolute = st$pending$absolute,
                                   text = vml_buf_value(st$pending$buf))
    st$pending <- NULL
    invisible(NULL)
  }

  n <- length(src)
  special <- which(src == VML_LT | src == VML_AMP)
  i <- 1L
  while (i <= n) {
    cp <- src[i]
    handled <- FALSE

    if (cp == VML_LT && i < n && (vml_is_ascii_letter(src[i + 1L]) || src[i + 1L] == VML_SLASH || src[i + 1L] == VML_BANG)) {
      j <- i + 1L
      quote <- 0L
      while (j <= n) {
        cj <- src[j]
        if (quote != 0L) {
          if (cj == quote) quote <- 0L
        } else if (cj == VML_DQUOTE || cj == VML_SQUOTE) {
          quote <- cj
        } else if (cj == VML_GT) break
        j <- j + 1L
      }
      if (j <= n) {
        raw <- vml_slice(src, i + 1L, j - 1L)
        i_next <- j + 1L
      } else {
        # An input that ends inside a tag: the incomplete tag is dropped, including the characters of
        # its name, the way a browser's eof-in-tag state drops it - so it contributes no newline, no
        # link and no image. ("<p" is the empty string, not "\n".)
        i <- n + 1L
        next
      }
      closing <- length(raw) >= 1L && raw[1L] == VML_SLASH
      name <- vml_tag_name(raw)

      if (identical(name, "title")) {
        if (!closing && !st$title_seen) {
          st$in_title <- TRUE
          st$title_seen <- TRUE
        } else if (closing && st$in_title) {
          st$in_title <- FALSE
        }
        i <- i_next
        next
      }
      if (identical(name, "img") && !closing) st$images <- st$images + 1L
      if (identical(name, "a")) {
        if (!closing) {
          # HTML has no nested anchors: a browser closes the open one and starts the new one, so the
          # outer link is reported with the text it had collected and the inner becomes the open one.
          if (!is.null(st$pending)) close_pending()
          href <- vml_find_href(raw)
          pend <- new.env(parent = emptyenv())
          pend$href <- href
          pend$absolute <- vml_href_is_absolute(href)
          pend$buf <- vml_buf_new()
          st$pending <- pend
        } else {
          close_pending()
        }
        i <- i_next
        next
      }
      if (name %in% VML_NEWLINE_TAGS) push_text(10L)
      i <- i_next
      next
    }

    if (cp == VML_AMP) {
      dec <- vml_decode_entity(src, i)
      if (!is.null(dec)) {
        push_text(dec$cps)
        i <- dec$next_index
        handled <- TRUE
      }
    }
    if (handled) next

    # a run of literal text up to the next '<' or '&'
    k <- findInterval(i, special) + 1L
    end <- if (k <= length(special)) special[k] else n + 1L
    push_text(vml_slice(src, i, end - 1L))
    i <- end
  }

  # an anchor still open at end of input is reported with the text it collected
  close_pending()

  links <- st$links[seq_len(st$links_n)]
  links <- lapply(links, function(l) {
    list(href = l$href, absolute = l$absolute, text = vml_cdata_restore(l$text, cdata))
  })
  list(title = vml_cdata_restore(vml_buf_value(st$title), cdata),
       text = vml_cdata_restore(vml_buf_value(st$text), cdata),
       links = links, images = st$images)
}

# ---------------------------------------------------------------------------------------------
# 6. text.fingerprint (docs/WORKERS.md section 4)
#
#    FNV-1a over 64 bits with no 64-bit integer type: the accumulator is two 32-bit words, and the
#    multiply by the FNV prime is done in base 2^16. With P = 16777216 * 2^16 + 435, the four limb
#    products are at most 65535 * 16777216 ~= 1.1e12, so every intermediate value is an exact double
#    and the carry chain never rounds. (h * P) mod 2^64 is then just the low four limbs.
# ---------------------------------------------------------------------------------------------

VML_FNV_PRIME_HI <- 16777216      # floor(1099511628211 / 2^16)
VML_FNV_PRIME_LO <- 435           # 1099511628211 mod 2^16
VML_FNV_OFFSET_HI <- 3421674724   # floor(14695981039346656037 / 2^32)
VML_FNV_OFFSET_LO <- 2216829733   # 14695981039346656037 mod 2^32
VML_CJK_RANGES <- list(c(0x3400L, 0x4DBFL), c(0x4E00L, 0x9FFFL), c(0xF900L, 0xFAFFL),
                       c(0x3040L, 0x30FFL), c(0xAC00L, 0xD7AFL))

vml_punct_cps <- function() A("!?,.;:'\"()[]{}<>-_/\\|*+=~`@#$%^&")
VML_PUNCT <- vml_punct_cps()

vml_is_cjk_mask <- function(cps) {
  m <- rep(FALSE, length(cps))
  for (r in VML_CJK_RANGES) m <- m | (cps >= r[1L] & cps <= r[2L])
  m
}

vml_tokenize_token <- function(piece) {
  m <- piece %in% VML_PUNCT
  n <- length(piece)
  a <- 1L
  while (a <= n && m[a]) a <- a + 1L
  if (a > n) return(list())
  b <- n
  while (b >= a && m[b]) b <- b - 1L
  t <- piece[a:b]
  if (length(t) == 0L) return(list())
  if (all(t %in% VML_PUNCT)) return(list())
  cjk <- vml_is_cjk_mask(t)
  out <- list()
  k <- 0L
  start <- 1L
  repeat {
    if (start > length(t)) break
    cls <- cjk[start]
    end <- start
    while (end + 1L <= length(t) && cjk[end + 1L] == cls) end <- end + 1L
    run <- t[start:end]
    if (cls) {
      if (length(run) == 1L) {
        k <- k + 1L
        out[[k]] <- run
      } else {
        for (p in seq_len(length(run) - 1L)) {
          k <- k + 1L
          out[[k]] <- c(run[p], run[p + 1L])
        }
      }
    } else {
      k <- k + 1L
      out[[k]] <- run
    }
    start <- end + 1L
  }
  out
}

vml_tokens_of <- function(cps) {
  out <- list()
  k <- 0L
  n <- length(cps)
  if (n == 0L) return(out)
  breaks <- c(0L, which(cps == VML_SPACE), n + 1L)
  for (t in seq_len(length(breaks) - 1L)) {
    piece <- vml_slice(cps, breaks[t] + 1L, breaks[t + 1L] - 1L)
    if (length(piece) == 0L) next
    toks <- vml_tokenize_token(piece)
    for (tk in toks) {
      k <- k + 1L
      out[[k]] <- tk
    }
  }
  out
}

vml_join_tokens <- function(toks) {
  m <- length(toks)
  total <- sum(vapply(toks, length, integer(1))) + m - 1L
  out <- integer(total)
  p <- 1L
  for (k in seq_len(m)) {
    v <- toks[[k]]
    L <- length(v)
    if (L > 0L) out[p:(p + L - 1L)] <- v
    p <- p + L
    if (k < m) {
      out[p] <- VML_SPACE
      p <- p + 1L
    }
  }
  out
}

vml_shingles_of <- function(tokens) {
  n <- length(tokens)
  if (n == 0L) return(list())
  if (n < 3L) return(list(vml_join_tokens(tokens)))
  lapply(seq_len(n - 2L), function(i) vml_join_tokens(tokens[i:(i + 2L)]))
}

vml_fnv1a64_cps <- function(cps) {
  hi <- VML_FNV_OFFSET_HI
  lo <- VML_FNV_OFFSET_LO
  bytes <- as.integer(vml_utf8_encode(cps))
  for (byte in bytes) {
    lo <- lo - (lo %% 256) + bitwXor(as.integer(lo %% 256), byte)
    a <- hi %/% 65536
    b <- hi %% 65536
    cc <- lo %/% 65536
    d <- lo %% 65536
    t0 <- d * VML_FNV_PRIME_LO
    t1 <- cc * VML_FNV_PRIME_LO + d * VML_FNV_PRIME_HI
    t2 <- b * VML_FNV_PRIME_LO + cc * VML_FNV_PRIME_HI
    t3 <- a * VML_FNV_PRIME_LO + b * VML_FNV_PRIME_HI
    d2 <- t0 %% 65536
    carry <- t0 %/% 65536
    v <- t1 + carry
    c2 <- v %% 65536
    carry <- v %/% 65536
    v <- t2 + carry
    b2 <- v %% 65536
    carry <- v %/% 65536
    v <- t3 + carry
    a2 <- v %% 65536
    hi <- a2 * 65536 + b2
    lo <- c2 * 65536 + d2
  }
  list(hi = hi, lo = lo)
}

vml_hex64 <- function(hi, lo) {
  # 16 hex digits, most significant first: hi fills positions 1-8, lo positions 9-16.
  digs <- character(16L)
  x <- hi
  for (k in 8:1) {
    digs[k] <- VML_HEX_DIGITS[[as.integer(x %% 16) + 1L]]
    x <- x %/% 16
  }
  x <- lo
  for (k in 16:9) {
    digs[k] <- VML_HEX_DIGITS[[as.integer(x %% 16) + 1L]]
    x <- x %/% 16
  }
  paste(digs, collapse = "")
}

vml_fingerprint_cps <- function(cps) {
  tokens <- vml_tokens_of(cps)
  shingles <- vml_shingles_of(tokens)
  counters <- integer(64L)
  for (s in shingles) {
    h <- vml_fnv1a64_cps(s)
    for (bit in 0:31) {
      set <- ((h$lo %/% (2^bit)) %% 2) >= 1
      counters[bit + 1L] <- counters[bit + 1L] + (if (set) 1L else -1L)
    }
    for (bit in 32:63) {
      set <- ((h$hi %/% (2^(bit - 32L))) %% 2) >= 1
      counters[bit + 1L] <- counters[bit + 1L] + (if (set) 1L else -1L)
    }
  }
  out_lo <- 0
  out_hi <- 0
  for (bit in 0:31) if (counters[bit + 1L] > 0L) out_lo <- out_lo + 2^bit
  for (bit in 32:63) if (counters[bit + 1L] > 0L) out_hi <- out_hi + 2^(bit - 32L)
  list(simhash = vml_hex64(out_hi, out_lo), tokens = length(tokens), shingles = length(shingles))
}

