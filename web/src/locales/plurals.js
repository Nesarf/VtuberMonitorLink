// locales/plurals.js — number-dependent word forms (BUGS #54)
//
// A single string per key cannot express "1 запись / 2 записи / 5 записей". These tables hold
// the extra forms, keyed `<key>_<Intl.PluralRules category>`, and `web/src/plural.js` picks the
// right one for the number at render time. Rules:
//
//   * The number goes *inside* the phrase (`{n} записей`) whenever the language needs the numeral
//     to be part of the wording; `countLabel()` prepends the number only when the value has no
//     `{n}` (which is how every locale behaved before this table existed).
//   * Only categories the language actually uses are listed — `Intl.PluralRules(code)` is the
//     authority, and `tools/i18n-plural-test.mjs` fails the build when a table is incomplete.
//   * These keys are looked up dynamically, never through a literal lookup call in the UI, so
//     coverage / proofread (which work on keys the UI references literally) are untouched. The
//     plain base key stays in `web/src/i18n.jsx` as the wording for languages that do not
//     inflect (zh / ja / ko) — those keep prepending the number, which is correct for them.
//   * zh-Hant / zh-HK / zh-TW inherit `zh`; en-GB / en-AU / en-CA inherit `en-US`;
//     es-419 / es-MX / es-AR inherit `es-ES`; pt-BR inherits `pt-PT`; fr-CA inherits `fr-FR`.
//   * Every form carries the number *inside* the phrase, including the three keys whose base
//     value already embeds `{n}` in Chinese (`cookieCount` / `cookieCountWithSession` /
//     `followersCount`): the numeral belongs in a fixed place in those wordings, so prepending
//     it would read as "+12 followers"-style junk in the inflected languages.
//   * Some locales count in units rather than by a noun (ru `шт.`, uk `шт.`, pl `szt.`,
//     sr `ком`). Those abbreviations are invariable, so all their categories repeat one wording:
//     that is correct for every number, not a form left out.
