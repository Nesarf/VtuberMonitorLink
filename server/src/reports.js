/** 极简 Markdown → HTML（导出用；先转义再替换，不做任何危险注入） */
export function markdownToHtml(md) {
  const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
  const inline = (s) =>
    s
      .replace(/`([^`]+)`/g, '<code>$1</code>')
      .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
      .replace(/(^|[^*])\*([^*]+)\*/g, '$1<em>$2</em>')
      .replace(/\[([^\]]+)\]\((https?:[^)\s]+)\)/g, '<a href="$2" target="_blank" rel="noreferrer">$1</a>');
  const lines = esc(md).split(/\r?\n/);
  const out = [];
  let inList = false;
  let inTable = false;
  const closeList = () => {
    if (inList) {
      out.push('</ul>');
      inList = false;
    }
  };
  for (const raw of lines) {
    const line = raw.trimEnd();
    if (/^\|/.test(line) && /\|$/.test(line)) {
      const cells = line.split('|').slice(1, -1).map((c) => c.trim());
      if (cells.every((c) => /^:?-{2,}:?$/.test(c))) continue;
      if (!inTable) {
        closeList();
        out.push('<table>');
        inTable = true;
        out.push(`<tr>${cells.map((c) => `<th>${inline(c)}</th>`).join('')}</tr>`);
        continue;
      }
      out.push(`<tr>${cells.map((c) => `<td>${inline(c)}</td>`).join('')}</tr>`);
      continue;
    }
    if (inTable) {
      out.push('</table>');
      inTable = false;
    }
    const h = /^(#{1,6})\s+(.*)$/.exec(line);
    if (h) {
      closeList();
      out.push(`<h${h[1].length}>${inline(h[2])}</h${h[1].length}>`);
      continue;
    }
    if (/^\s*[-*]\s+/.test(line)) {
      if (!inList) {
        out.push('<ul>');
        inList = true;
      }
      out.push(`<li>${inline(line.replace(/^\s*[-*]\s+/, ''))}</li>`);
      continue;
    }
    if (/^\s*>\s?/.test(line)) {
      closeList();
      out.push(`<blockquote>${inline(line.replace(/^\s*>\s?/, ''))}</blockquote>`);
      continue;
    }
    if (/^(-{3,}|\*{3,})$/.test(line.trim())) {
      closeList();
      out.push('<hr/>');
      continue;
    }
    if (!line.trim()) {
      closeList();
      out.push('');
      continue;
    }
    closeList();
    out.push(`<p>${inline(line)}</p>`);
  }
  closeList();
  if (inTable) out.push('</table>');
  return out.join('\n');
}

export function exportReport(cfg, name, format = 'html') {
  // 导出永远基于 markdown 源文，所以报告主文件换任何格式（html/adoc/json）都不影响导出
  const md = markdownSource(cfg, name);
  if (md === null) return null;
  const base = path.basename(name).replace(/\.[^.]+$/, '');
  if (format === 'docx') {
    return {
      file: `${base}.docx`,
      mime: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
      buffer: buildDocx({ title: base, markdown: md }),
    };
  }
  if (format === 'json') {
    return {
      file: `${base}.json`,
      mime: 'application/json; charset=utf-8',
      body: JSON.stringify({ name: path.basename(name), exportedAt: new Date().toISOString(), markdown: md }, null, 2),
    };
  }
  return { file: `${base}.html`, mime: 'text/html; charset=utf-8', body: htmlShell(base, md) };
}

/** 报告全文检索 / full-text search across reports */
export function searchReports(cfg, query, limit = 50) {
  const q = String(query ?? '').trim();
  if (!q) return [];
  const dir = resolveDir(cfg, 'reportsDir');
  if (!fs.existsSync(dir)) return [];
  const needle = q.toLowerCase();
  const hits = [];
  // 不再只搜 .md：源 .json 也在内，这样换任何输出格式都搜得到
  for (const f of fs.readdirSync(dir).filter((x) => REPORT_EXTS.some((e) => x.endsWith(`.${e}`)))) {
    const text = fs.readFileSync(path.join(dir, f), 'utf8');
    const lines = text.split(/\r?\n/);
    const matches = [];
    lines.forEach((line, i) => {
      if (line.toLowerCase().includes(needle)) {
        matches.push({ line: i + 1, text: line.trim().slice(0, 240) });
      }
    });
    if (matches.length) hits.push({ name: f, count: matches.length, matches: matches.slice(0, 20) });
    if (hits.length >= limit) break;
  }
  return hits.sort((a, b) => b.count - a.count);
}

