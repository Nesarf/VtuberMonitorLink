vml_script_path <- function() {
  a <- commandArgs(trailingOnly = FALSE)
  f <- grep("^--file=", a, value = TRUE)
  if (length(f) == 0L) return(NULL)
  sub("^--file=", "", f[1L])
}

vml_load_tables <- function() {
  p <- vml_script_path()
  path <- if (is.null(p)) "tables.generated.R" else file.path(dirname(p), "tables.generated.R")
  if (!file.exists(path)) {
    vml_fatal("error: ", path, " is missing; build it with: node workers/r/build.mjs")
  }
  source(path, local = FALSE)
  if (!exists("VML_LOWER", inherits = TRUE) || !exists("VML_FOLD", inherits = TRUE)) {
    vml_fatal("error: ", path, " did not define VML_LOWER and VML_FOLD")
  }
  if (length(VML_LOWER) < 592L || length(VML_FOLD) < 592L) {
    vml_fatal("error: ", path, " is not the table shape this worker expects (length >= 592)")
  }
  invisible(TRUE)
}

# ---------------------------------------------------------------------------------------------
# 3. JSON: a hand-rolled reader and writer. Base R has neither, and the protocol only needs
#    objects, arrays, strings with the full escape set (including \uXXXX with surrogate pairs),
#    numbers echoed verbatim, booleans and null.
#
#    A parsed value is a list(t = <type>, v = <value>):
#      null  -> v NULL            bool -> v TRUE/FALSE        num -> v code points of the literal
#      str   -> v code point vector                            arr -> v list of values
#      obj   -> v named list of values (names are ASCII)
# ---------------------------------------------------------------------------------------------

vml_jnull <- function() list(t = "null", v = NULL)
vml_jbool <- function(b) list(t = "bool", v = isTRUE(b))
vml_jnum <- function(n) list(t = "num", v = A(vml_format_int(n)))
vml_jstr <- function(cps) list(t = "str", v = as.integer(cps))
vml_jarr <- function(items) list(t = "arr", v = items)
vml_jobj <- function(fields) list(t = "obj", v = fields)

vml_format_int <- function(x) {
  x <- as.numeric(x)
  if (!is.finite(x) || x < 0) return("0")
  if (x == 0) return("0")
  digs <- character(0)
  while (x > 0) {
    digs <- c(digs, VML_HEX_DIGITS[[as.integer(x %% 10) + 1L]])
    x <- x %/% 10
  }
  paste(rev(digs), collapse = "")
}

vml_json_reader <- function(cps) {
  st <- new.env(parent = emptyenv())
  st$cps <- cps
  st$n <- length(cps)
  st$i <- 1L

  st$peek <- function() if (st$i <= st$n) st$cps[st$i] else NA_integer_
  st$skip_ws <- function() {
    while (st$i <= st$n) {
      cp <- st$cps[st$i]
      if (cp == 32L || cp == 9L || cp == 10L || cp == 13L) st$i <- st$i + 1L else break
    }
  }
  st$fail <- function(what) stop(structure(class = c("vml_json_error", "error", "condition"),
                                           list(message = what, call = NULL)))
  st$parse_value <- function() {
    st$skip_ws()
    if (st$i > st$n) st$fail("unexpected end of input")
    cp <- st$cps[st$i]
    if (cp == 123L) return(st$parse_object())
    if (cp == 91L) return(st$parse_array())
    if (cp == 34L) return(vml_jstr(st$parse_string()))
    if (cp == 116L) { st$expect_word("true"); return(vml_jbool(TRUE)) }
    if (cp == 102L) { st$expect_word("false"); return(vml_jbool(FALSE)) }
    if (cp == 110L) { st$expect_word("null"); return(vml_jnull()) }
    if (cp == 45L || (cp >= 48L && cp <= 57L)) return(st$parse_number())
    st$fail("unexpected character in JSON")
  }
  st$expect_word <- function(w) {
    need <- A(w)
    if (st$i + length(need) - 1L > st$n) st$fail("unexpected end of input")
    if (!all(st$cps[st$i:(st$i + length(need) - 1L)] == need)) st$fail(paste0("expected ", w))
    st$i <- st$i + length(need)
    invisible(NULL)
  }
  st$parse_number <- function() {
    start <- st$i
    while (st$i <= st$n) {
      cp <- st$cps[st$i]
      if ((cp >= 48L && cp <= 57L) || cp == 45L || cp == 43L || cp == 46L || cp == 101L || cp == 69L) {
        st$i <- st$i + 1L
      } else break
    }
    if (st$i == start) st$fail("malformed number")
    list(t = "num", v = st$cps[start:(st$i - 1L)])
  }
  st$parse_string <- function() {
    st$i <- st$i + 1L # opening quote
    out <- vector("list", 0L)
    k <- 0L
    repeat {
      if (st$i > st$n) st$fail("unterminated string")
      cp <- st$cps[st$i]
      if (cp == 34L) { st$i <- st$i + 1L; break }
      if (cp == 92L) {
        st$i <- st$i + 1L
        if (st$i > st$n) st$fail("unterminated escape")
        e <- st$cps[st$i]
        st$i <- st$i + 1L
        if (e == 117L) { # \uXXXX, with surrogate pairs joined into one code point
          if (st$i + 3L > st$n) st$fail("truncated \\u escape")
          hx <- st$cps[st$i:(st$i + 3L)]
          if (!all(vml_is_hex_digit(hx))) st$fail("malformed \\u escape")
          st$i <- st$i + 4L
          v <- 0L
          for (d in hx) v <- v * 16L + vml_hex_value(d)
          if (v >= 0xD800L && v <= 0xDBFFL && st$i + 5L <= st$n &&
              st$cps[st$i] == 92L && st$cps[st$i + 1L] == 117L &&
              all(vml_is_hex_digit(st$cps[(st$i + 2L):(st$i + 5L)]))) {
            lo <- 0L
            for (d in st$cps[(st$i + 2L):(st$i + 5L)]) lo <- lo * 16L + vml_hex_value(d)
            if (lo >= 0xDC00L && lo <= 0xDFFFL) {
              v <- 0x10000L + (v - 0xD800L) * 0x400L + (lo - 0xDC00L)
              st$i <- st$i + 6L
            }
          }
          k <- k + 1L
          out[[k]] <- as.integer(v)
          next
        }
        simple <- switch(as.character(e),
                         "34" = 34L, "92" = 92L, "47" = 47L, "98" = 8L, "102" = 12L,
                         "110" = 10L, "114" = 13L, "116" = 9L, NA_integer_)
        if (is.na(simple)) st$fail("unknown string escape")
        k <- k + 1L
        out[[k]] <- simple
        next
      }
      k <- k + 1L
      out[[k]] <- as.integer(cp)
      st$i <- st$i + 1L
    }
    if (k == 0L) integer(0) else unlist(out[seq_len(k)], use.names = FALSE)
  }
  st$parse_array <- function() {
    st$i <- st$i + 1L
    st$skip_ws()
    items <- list()
    if (st$peek() == 93L) { st$i <- st$i + 1L; return(vml_jarr(items)) }
    repeat {
      items[[length(items) + 1L]] <- st$parse_value()
      st$skip_ws()
      cp <- st$peek()
      if (is.na(cp)) st$fail("unterminated array")
      st$i <- st$i + 1L
      if (cp == 93L) break
      if (cp != 44L) st$fail("expected , or ] in array")
    }
    vml_jarr(items)
  }
  st$parse_object <- function() {
    st$i <- st$i + 1L
    st$skip_ws()
    keys <- character(0)
    vals <- list()
    if (st$peek() == 125L) { st$i <- st$i + 1L; return(vml_jobj(list())) }
    repeat {
      st$skip_ws()
      if (st$peek() != 34L) st$fail("expected a string key")
      kcps <- st$parse_string()
      key <- if (length(kcps) == 0L) "" else rawToChar(as.raw(as.integer(kcps)))
      st$skip_ws()
      if (st$peek() != 58L) st$fail("expected : in object")
      st$i <- st$i + 1L
      val <- st$parse_value()
      keys <- c(keys, key)
      vals[[length(vals) + 1L]] <- val
      st$skip_ws()
      cp <- st$peek()
      if (is.na(cp)) st$fail("unterminated object")
      st$i <- st$i + 1L
      if (cp == 125L) break
      if (cp != 44L) st$fail("expected , or } in object")
    }
    names(vals) <- keys
    vml_jobj(vals)
  }

  st$skip_ws()
  value <- st$parse_value()
  st$skip_ws()
  if (st$i <= st$n) st$fail("trailing characters after the JSON value")
  value
}

vml_json_string_cps <- function(cps) {
  out <- c(VML_DQUOTE)
  for (cp in cps) {
    cp <- as.integer(cp)
    if (cp == 34L) out <- c(out, 92L, 34L)
    else if (cp == 92L) out <- c(out, 92L, 92L)
    else if (cp == 8L) out <- c(out, 92L, 98L)
    else if (cp == 9L) out <- c(out, 92L, 116L)
    else if (cp == 10L) out <- c(out, 92L, 110L)
    else if (cp == 12L) out <- c(out, 92L, 102L)
    else if (cp == 13L) out <- c(out, 92L, 114L)
    else if (cp < 32L || (cp >= 0xD800L && cp <= 0xDFFFL)) {
      out <- c(out, A(sprintf("\\u%04x", cp)))
    } else out <- c(out, cp)
  }
  c(out, VML_DQUOTE)
}

vml_json_encode <- function(node) {
  switch(node$t,
    "null" = A("null"),
    "bool" = if (isTRUE(node$v)) A("true") else A("false"),
    "num" = node$v,
    "str" = vml_json_string_cps(node$v),
    "arr" = {
      parts <- lapply(node$v, vml_json_encode)
      out <- c(A("["))
      for (i in seq_along(parts)) {
        if (i > 1L) out <- c(out, A(","))
        out <- c(out, parts[[i]])
      }
      c(out, A("]"))
    },
    "obj" = {
      keys <- names(node$v)
      out <- c(A("{"))
      for (i in seq_along(node$v)) {
        if (i > 1L) out <- c(out, A(","))
        out <- c(out, vml_json_string_cps(A(keys[[i]])), A(":"), vml_json_encode(node$v[[i]]))
      }
      c(out, A("}"))
    },
    stop("unsupported JSON node")
  )
}

vml_obj_get <- function(node, key) {
  if (is.null(node) || !identical(node$t, "obj")) return(NULL)
  idx <- match(key, names(node$v))
  if (is.na(idx)) return(NULL)
  node$v[[idx]]
}

vml_as_string <- function(node) {
  if (is.null(node) || !identical(node$t, "str")) return(NULL)
  node$v
}

