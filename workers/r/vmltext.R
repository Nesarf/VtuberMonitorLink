#!/usr/bin/env Rscript
# =============================================================================================
# workers/r/vmltext.R - the R implementation of the three text capabilities of docs/WORKERS.md:
# text.normalize (section 2), text.extract (section 3) and text.fingerprint (section 4), behind
# the JSON-Lines protocol of section 1 (one JSON object per line, UTF-8, describe/invoke/shutdown,
# ok/error envelopes, stdout carries protocol lines and nothing else, stderr carries English
# diagnostics, and stdout is flushed after every response).
#
# Base R only. No package is loaded, nothing is downloaded, and no runtime library's Unicode data
# is consulted: the case and fold tables come from workers/spec/*.json through
# workers/r/tables.generated.R, generated by workers/r/build.mjs. tolower() and toupper() are
# deliberately never called - four languages applying their own case tables is exactly how four
# implementations of this contract end up disagreeing.
#
# Four decisions worth stating before the code, because each one is a place where the obvious R
# answer is wrong:
#
#  1. THIS FILE IS PURE ASCII, AND SO IS THE GENERATED TABLE FILE. R parses a source file using the
#     session's encoding, and a source file that is UTF-8 on one machine is GBK on the next. Every
#     literal here is ASCII, and every non-ASCII code point that matters (the case and fold tables,
#     the mapping targets, the entity values, the expected selfcheck results) is written as a
#     number.
#
#  2. TEXT IS AN INTEGER VECTOR OF CODE POINTS, NEVER AN R STRING. R strings carry an encoding mark
#     and are transcoded to the session's native encoding on output, which on a non-UTF-8 Windows
#     machine would corrupt exactly the CJK text the contract insists must survive unchanged. So
#     the worker decodes stdin bytes to code points itself (hand-rolled UTF-8 decoder, so an
#     invalid sequence cannot make R abort), works on integer vectors, and encodes the answer back
#     to UTF-8 bytes itself. nchar(), substr(), strsplit(), regexpr() and the tolower() family are
#     never called: they are all locale- and encoding-sensitive.
#
#  3. 64-BIT ARITHMETIC WITHOUT 64-BIT INTEGERS. R's integer is 32-bit and R's double is exact only
#     up to 2^53, so (h * 1099511628211) %% 2^64 in doubles is wrong - the product needs 105 bits.
#     The accumulator is therefore kept as two 32-bit words (hi, lo) held in doubles, and each
#     multiplication splits the prime into 16-bit halves, P = 16777216 * 2^16 + 435, so that the
#     largest intermediate value is about 1.1e12 - three orders of magnitude below 2^53, and every
#     step is exact. See vml_fnv1a64_cps() below and the README.
#
#  4. LINE ENDINGS ON WINDOWS. The contract says LF. R's stdout is a text-mode stream, and on
#     Windows the C runtime rewrites every LF written to it as CR LF; base R exposes no _setmode,
#     "writeBin" refuses a terminal connection ("can only write to a binary connection"),
#     file("stdout", "wb") is not special-cased on R 4.6 and creates a file literally named
#     "stdout", and calling _setmode() on ucrtbase.dll through .C() does not clear the translation
#     flag of the already-initialised FILE stream. So this worker's lines end in CR LF on Windows.
#     The JSON content is byte-identical and JSON.parse() treats the CR as whitespace, so the
#     conformance harness is unaffected; it is reported in the README rather than papered over.
#
# Usage (the host appends the capability; see docs/WORKERS.md section 1.1):
#   Rscript workers/r/vmltext.R --capability text.normalize
#   Rscript workers/r/vmltext.R --capability text.extract
#   Rscript workers/r/vmltext.R --capability text.fingerprint
#   Rscript workers/r/vmltext.R --selfcheck
# =============================================================================================

