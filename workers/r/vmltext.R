# ---------------------------------------------------------------------------------------------
# 1. UTF-8 codec, hand-rolled on purpose. Decoding never raises: an invalid byte becomes U+FFFD,
#    as a permissive decoder would, instead of aborting the worker.
# ---------------------------------------------------------------------------------------------

vml_utf8_decode <- function(bytes) {
  n <- length(bytes)
  if (n == 0L) return(integer(0))
  b <- as.integer(bytes)
  if (all(b < 128L)) return(b)
  out <- vector("list", 0L)
  k <- 0L
  i <- 1L
  while (i <= n) {
    b1 <- b[i]
    if (b1 < 128L) {
      # copy the whole ASCII run at once
      j <- i
      while (j <= n && b[j] < 128L) j <- j + 1L
      k <- k + 1L
      out[[k]] <- b[i:(j - 1L)]
      i <- j
      next
    }
    need <- if (b1 >= 240L) 4L else if (b1 >= 224L) 3L else if (b1 >= 192L) 2L else 0L
    ok <- need > 0L && (i + need - 1L) <= n
    if (ok) {
      cont <- b[(i + 1L):(i + need - 1L)]
      ok <- all(cont >= 128L & cont <= 191L)
    }
    if (ok && need == 2L) ok <- b1 >= 194L
    if (ok && need == 3L) ok <- !(b1 == 224L && b[i + 1L] < 160L)
    if (ok && need == 4L) ok <- b1 <= 244L && !(b1 == 240L && b[i + 1L] < 144L) && !(b1 == 244L && b[i + 1L] > 143L)
    if (!ok) {
      k <- k + 1L
      out[[k]] <- 0xFFFDL
      i <- i + 1L
      next
    }
    # switch() counts its alternatives from 1, so the index is need - 1: 2-byte, 3-byte, 4-byte.
    cp <- switch(need - 1L,
      (b1 - 192L) * 64L + (b[i + 1L] - 128L),
      (b1 - 224L) * 4096L + (b[i + 1L] - 128L) * 64L + (b[i + 2L] - 128L),
      (b1 - 240L) * 262144L + (b[i + 1L] - 128L) * 4096L + (b[i + 2L] - 128L) * 64L + (b[i + 3L] - 128L)
    )
    k <- k + 1L
    out[[k]] <- as.integer(cp)
    i <- i + need
  }
  unlist(out[seq_len(k)], use.names = FALSE)
}

# Lone surrogates and out-of-range values become U+FFFD, which is what Node's UTF-8 encoder does
# with them; the contract's input is well-formed, so this only keeps a malformed byte out of the
# output instead of producing invalid UTF-8.
vml_utf8_encode <- function(cps) {
  n <- length(cps)
  if (n == 0L) return(raw(0))
  cp <- as.integer(cps)
  bad <- is.na(cp) | cp < 0L | cp > 0x10FFFFL | (cp >= 0xD800L & cp <= 0xDFFFL)
  if (any(bad)) cp[bad] <- 0xFFFDL
  len <- ifelse(cp < 0x80L, 1L, ifelse(cp < 0x800L, 2L, ifelse(cp < 0x10000L, 3L, 4L)))
  out <- integer(sum(len))
  pos <- cumsum(len) - len + 1L
  s1 <- len == 1L
  if (any(s1)) out[pos[s1]] <- cp[s1]
  s2 <- len == 2L
  if (any(s2)) {
    out[pos[s2]] <- 0xC0L + cp[s2] %/% 64L
    out[pos[s2] + 1L] <- 0x80L + cp[s2] %% 64L
  }
  s3 <- len == 3L
  if (any(s3)) {
    out[pos[s3]] <- 0xE0L + cp[s3] %/% 4096L
    out[pos[s3] + 1L] <- 0x80L + (cp[s3] %/% 64L) %% 64L
    out[pos[s3] + 2L] <- 0x80L + cp[s3] %% 64L
  }
  s4 <- len == 4L
  if (any(s4)) {
    out[pos[s4]] <- 0xF0L + cp[s4] %/% 262144L
    out[pos[s4] + 1L] <- 0x80L + (cp[s4] %/% 4096L) %% 64L
    out[pos[s4] + 2L] <- 0x80L + (cp[s4] %/% 64L) %% 64L
    out[pos[s4] + 3L] <- 0x80L + cp[s4] %% 64L
  }
  as.raw(out)
}

# A code point vector as an R string holding exactly those UTF-8 bytes. rawToChar() leaves the
# encoding mark unset ("unknown" = native), and R writes an unmarked string byte for byte without
# transcoding, which is precisely what a UTF-8 transport needs on a GBK-locale machine.
vml_to_native_bytes_string <- function(cps) rawToChar(vml_utf8_encode(cps))

# Readable, ASCII-only rendering for diagnostics and the selfcheck report: a console in a non-UTF-8
# code page cannot be trusted to show CJK correctly, and a selfcheck that cannot be read is useless.
vml_repr <- function(cps) {
  if (length(cps) == 0L) return("\"\"")
  parts <- character(length(cps))
  for (i in seq_along(cps)) {
    cp <- cps[i]
    parts[i] <- if (cp >= 32L && cp < 127L && cp != 34L && cp != 92L) {
      rawToChar(as.raw(as.integer(cp)))
    } else if (cp == 34L) {
      "\\\""
    } else if (cp == 92L) {
      "\\\\"
    } else if (cp < 0x10000L) {
      sprintf("\\u%04x", as.integer(cp))
    } else {
      sprintf("\\U%08x", as.integer(cp))
    }
  }
  paste0("\"", paste(parts, collapse = ""), "\"")
}

# ---------------------------------------------------------------------------------------------
# 2. The shared tables. VML_LOWER and VML_FOLD are sourced from tables.generated.R, which
#    workers/r/build.mjs emits from workers/spec/latin-lower.json and latin-fold.json. Nothing in
#    this file falls back to an R case table: if the generated file is missing, the worker refuses
